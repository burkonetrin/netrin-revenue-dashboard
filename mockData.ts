function buildClient(seed: Omit<ClientMock, "saude" | "consumoMedioPct"> & {
  consumoMedioPct: number;
}): ClientMock {
  const consumoMedioPct =
    seed.contracts.reduce(
      (acc, c) => acc + c.consumoMedioFranquiasPct,
      0,
    ) / seed.contracts.length;
  return {
    ...seed,
    consumoMedioPct,
    saude: healthFromConsumption(consumoMedioPct),
  };
}

